const assert = require("node:assert/strict");
const { coordinate, validateLocation } = require("../src/server/timeclock-location");
const settings = { "timeclock.store_latitude": "-22.8", "timeclock.store_longitude": "-43.3", "timeclock.allowed_radius_meters": "15" };
const body = { latitude: -22.8, longitude: -43.3, accuracy: 5 };
assert.equal(coordinate("", 90), null);
assert.equal(coordinate(null, 90), null);
assert.equal(coordinate(false, 90), null);
assert.equal(coordinate([], 90), null);
assert.equal(coordinate("Infinity", 90), null);
assert.equal(coordinate("91", 90), null);
assert.equal(coordinate("0", 90), 0);
assert.equal(validateLocation({}, body).locationStatus, "Localizacao registrada");
assert.equal(validateLocation({}, body).distanceMeters, null);
assert.match(validateLocation(settings, { ...body, latitude: null }).error, /Localizacao invalida/);
assert.equal(validateLocation(settings, { ...body, accuracy: 5000 }).accuracy, 5000);
for (const accuracy of [null, 0, -5, undefined, "invalid"]) assert.equal(validateLocation(settings, { ...body, accuracy }).accuracy, null);
const atDistance = (meters) => ({ ...body, latitude: body.latitude + meters / 6371000 * 180 / Math.PI });
assert.equal(validateLocation(settings, body).distanceMeters, 0);
assert.equal(validateLocation(settings, atDistance(14.9)).locationStatus, "Localizacao registrada");
assert.equal(validateLocation(settings, atDistance(15.1)).error, undefined);
assert.equal(validateLocation(settings, atDistance(100000)).distanceMeters, 100000);
assert.equal(validateLocation({ ...settings, "timeclock.allowed_radius_meters": "1" }, atDistance(20)).error, undefined);
assert.equal(validateLocation({}, { latitude: 0, longitude: 0 }).latitude, 0);
assert.match(validateLocation(settings, { ...body, longitude: 181 }).error, /Localizacao invalida/);
const fs = require("node:fs");
const vm = require("node:vm");
const frontend = fs.readFileSync(require("node:path").join(__dirname, "../timeclock/app.js"), "utf8");
const context = vm.createContext({});
vm.runInContext(frontend.slice(frontend.indexOf("function locationDetails("), frontend.indexOf("function adminView(")), context);
const html = context.locationDetails({ ...body, distanceMeters: 1200 });
assert.match(html, /Latitude: -22.800000/);
assert.match(html, /Longitude: -43.300000/);
assert.match(html, /https:\/\/www.google.com\/maps\?q=-22.8,-43.3/);
assert.doesNotMatch(context.locationDetails({ latitude: null, longitude: null }), /google.com/);
console.log("Timeclock location: no geofence or precision block, optional reference, valid coordinates and administrator map passed.");
