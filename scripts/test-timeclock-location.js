const assert = require("node:assert/strict");
const { coordinate, validateLocation } = require("../src/server/timeclock-location");
const settings = { "timeclock.store_latitude": "-22.8", "timeclock.store_longitude": "-43.3", "timeclock.allowed_radius_meters": "15" };
const body = { latitude: -22.8, longitude: -43.3, accuracy: 5 };
assert.equal(coordinate("", 90), null);
assert.equal(coordinate(null, 90), null);
assert.equal(coordinate(false, 90), null);
assert.equal(coordinate([], 90), null);
assert.equal(coordinate("Infinity", 90), null);
assert.equal(coordinate("91", 90), null);
assert.equal(coordinate("0", 90), 0);
assert.match(validateLocation({}, body).error, /salvar a localizacao/);
assert.match(validateLocation(settings, { ...body, latitude: null }).error, /Localizacao invalida/);
assert.match(validateLocation(settings, { ...body, accuracy: 50 }).error, /GPS impreciso/);
assert.match(validateLocation(settings, { ...body, accuracy: null }).error, /GPS impreciso/);
assert.match(validateLocation(settings, { ...body, accuracy: 0 }).error, /GPS impreciso/);
const atDistance = (meters) => ({ ...body, latitude: body.latitude + meters / 6371000 * 180 / Math.PI });
assert.equal(validateLocation(settings, body).distanceMeters, 0);
assert.equal(validateLocation(settings, atDistance(14.9)).locationStatus, "Dentro do raio");
assert.match(validateLocation(settings, atDistance(15.1)).error, /fora do local permitido/, "Do not round before validating the boundary");
assert.match(validateLocation({ ...settings, "timeclock.allowed_radius_meters": "150" }, atDistance(20)).error, /fora do local permitido/, "Old large radii cannot bypass the new maximum");
console.log("Timeclock location: missing coordinates, precise GPS, strict radius and old configuration passed.");
